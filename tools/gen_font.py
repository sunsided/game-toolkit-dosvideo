#!/usr/bin/env python3
"""Generate raw CP437 8x16 font data from a PSF2 console font (default: console-setup Uni2-VGA16).

Output: 256 glyphs * 16 bytes, one byte per row, MSB = leftmost pixel.
The font source (u_vga16.bdf, Dmitry Bolkhovityanov) is MIT licensed; see fonts/LICENSE-vga16.txt.
"""
import gzip, struct, sys

CP437_LOW = "\u0000☺☻♥♦♣♠•◘○◙♂♀♪♫☼►◄↕‼¶§▬↨↑↓→←∟↔▲▼"

def cp437_to_unicode(b):
    if b < 0x20:
        return CP437_LOW[b] if b else None
    if b == 0x7F:
        return "⌂"
    return bytes([b]).decode("cp437")

def load_psf1(data):
    mode, h = data[2], data[3]
    n = 512 if mode & 1 else 256
    glyphs = [data[4 + i * h: 4 + (i + 1) * h] for i in range(n)]
    table = {}
    if mode & 2:
        pos = 4 + n * h
        idx = 0
        seq = False
        while idx < n and pos + 1 < len(data):
            (u,) = struct.unpack("<H", data[pos:pos + 2])
            pos += 2
            if u == 0xFFFF:
                idx += 1
                seq = False
            elif u == 0xFFFE:
                seq = True
            elif not seq:
                table.setdefault(chr(u), idx)
    return glyphs, table, 8, h

def load_psf2(path):
    data = gzip.open(path).read() if path.endswith(".gz") else open(path, "rb").read()
    if data[:2] == b"\x36\x04":
        return load_psf1(data)
    magic, ver, hdr, flags, n, bpg, h, w = struct.unpack("<IIIIIIII", data[:32])
    assert magic == 0x864AB572, "not PSF2"
    glyphs = [data[hdr + i * bpg: hdr + (i + 1) * bpg] for i in range(n)]
    table = {}
    if flags & 1:
        pos = hdr + n * bpg
        rest = data[pos:]
        idx = 0
        i = 0
        while idx < n and i < len(rest):
            j = rest.index(b"\xff", i)
            entry = rest[i:j]
            # split sequences at 0xFE, only take the single code points before it
            singles = entry.split(b"\xfe")[0].decode("utf-8", "replace")
            for ch in singles:
                table.setdefault(ch, idx)
            idx += 1
            i = j + 1
    return glyphs, table, w, h


