def hand_glyph(code):
    if code == 0xDC:
        return bytes([0] * 8 + [0xFF] * 8)
    if code == 0xDF:
        return bytes([0xFF] * 8 + [0] * 8)
    if code == 0xDD:
        return bytes([0xF0] * 16)
    if code == 0xDE:
        return bytes([0x0F] * 16)
    art = HAND.get(code)
    if art is None:
        return None
    rows = art.strip().splitlines()
    assert len(rows) == 16, (hex(code), len(rows))
    out = bytearray()
    for r in rows:
        assert len(r) == 8, (hex(code), r)
        v = 0
        for i, ch in enumerate(r):
            if ch == "#":
                v |= 0x80 >> i
        out.append(v)
    return bytes(out)

# CP437 box drawing 0xB3-0xDA: (up, down, left, right), 0 none / 1 single / 2 double.
# Console fonts map the double-line code points to single-line fallbacks, so these are drawn
# procedurally in IBM VGA geometry: single strokes at row 7 / columns 3-4, double strokes at
# rows 5 and 7 / columns 2-3 and 5-6, with the IBM rules for where lines meet.
BOX = {
    0xB3: (1, 1, 0, 0), 0xB4: (1, 1, 1, 0), 0xB5: (1, 1, 2, 0), 0xB6: (2, 2, 1, 0),
    0xB7: (0, 2, 1, 0), 0xB8: (0, 1, 2, 0), 0xB9: (2, 2, 2, 0), 0xBA: (2, 2, 0, 0),
    0xBB: (0, 2, 2, 0), 0xBC: (2, 0, 2, 0), 0xBD: (2, 0, 1, 0), 0xBE: (1, 0, 2, 0),
    0xBF: (0, 1, 1, 0), 0xC0: (1, 0, 0, 1), 0xC1: (1, 0, 1, 1), 0xC2: (0, 1, 1, 1),
    0xC3: (1, 1, 0, 1), 0xC4: (0, 0, 1, 1), 0xC5: (1, 1, 1, 1), 0xC6: (1, 1, 0, 2),
    0xC7: (2, 2, 0, 1), 0xC8: (2, 0, 0, 2), 0xC9: (0, 2, 0, 2), 0xCA: (2, 0, 2, 2),
    0xCB: (0, 2, 2, 2), 0xCC: (2, 2, 0, 2), 0xCD: (0, 0, 2, 2), 0xCE: (2, 2, 2, 2),
    0xCF: (1, 0, 2, 2), 0xD0: (2, 0, 1, 1), 0xD1: (0, 1, 2, 2), 0xD2: (0, 2, 1, 1),
    0xD3: (2, 0, 0, 1), 0xD4: (1, 0, 0, 2), 0xD5: (0, 1, 0, 2), 0xD6: (0, 2, 0, 1),
    0xD7: (2, 2, 1, 1), 0xD8: (1, 1, 2, 2), 0xD9: (1, 0, 1, 0), 0xDA: (0, 1, 0, 1),
}

def box_glyph(code):
    U, D, L, R = BOX[code]
    px = set()
    def v(cols, y0, y1):
        for x in cols:
            for y in range(y0, y1 + 1):
                px.add((x, y))
    def h(row, x0, x1):
        for x in range(x0, x1 + 1):
            px.add((x, row))
    horiz = L or R
    # Vertical arms.
    if U == 1:
        v((3, 4), 0, 7 if horiz and not D else 15 if D else 7)
    if D == 1:
        v((3, 4), 5 if 2 in (L, R) else 7 if horiz else 0, 15)
    if U == 2:
        le = 5 if L == 2 else 7 if L == 1 else (7 if R else 15)
        re = 5 if R == 2 else 7 if R == 1 else (7 if L else 15)
        v((2, 3), 0, le)
        v((5, 6), 0, re)
    if D == 2:
        ls = 7 if L else (5 if R == 2 else 7 if R == 1 else 0)
        rs = 7 if R else (5 if L == 2 else 7 if L == 1 else 0)
        v((2, 3), ls, 15)
        v((5, 6), rs, 15)
    # Horizontal arms.
    if L == 1:
        end = 7 if (U == 2 and D == 2 and R == 1) else 3 if (U == 2 and D == 2) else 6 if 2 in (U, D) else 4 if (U or D) else 7
        h(7, 0, end)
    if R == 1:
        start = 0 if (U == 2 and D == 2 and L == 1) else 5 if (U == 2 and D == 2) else 2 if 2 in (U, D) else 3 if (U or D) else 0
        h(7, start, 7)
    if L == 2:
        h(5, 0, 3 if U == 2 else 4 if (U == 1 or D == 1) else 6 if D == 2 else 7)
        h(7, 0, 3 if D == 2 else 4 if (D == 1 or U == 1) else 6 if U == 2 else 7)
    if R == 2:
        h(5, 5 if U == 2 else 3 if (U == 1 or D == 1) else 2 if D == 2 else 0, 7)
        h(7, 5 if D == 2 else 3 if (D == 1 or U == 1) else 2 if U == 2 else 0, 7)
    out = bytearray(16)
    for (x, y) in px:
        out[y] |= 0x80 >> x
    return bytes(out)

def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/consolefonts/Uni2-VGA16.psf.gz"
    out = sys.argv[2] if len(sys.argv) > 2 else "crates/dosvideo/fonts/cp437_8x16.bin"
    glyphs, table, w, h = load_psf2(src)
    assert w == 8 and h == 16, (w, h)
    res = bytearray()
    missing = []
    for b in range(256):
        if b in BOX:
            res += box_glyph(b)
            continue
        u = cp437_to_unicode(b)
        if u is None:
            res += bytes(16)
            continue
        gi = table.get(u)
        if gi is None:
            hg = hand_glyph(b)
            if hg is None:
                missing.append((hex(b), u))
                hg = bytes(16)
            res += hg
        else:
            res += glyphs[gi]
    open(out, "wb").write(res)
    print("wrote", out, len(res), "missing:", missing)

main()
